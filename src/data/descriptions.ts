/**
 * MBTI 유형으로 설명 조회
 */
export function getTypeDescription(type: MBTIType): TypeDescription {
  return typeDescriptions[type];
}

/**
 * MBTI 유형의 간단한 설명 반환
 */
export function getShortDescription(type: MBTIType): string {
  const desc = typeDescriptions[type];
  return `${desc.title}: ${desc.description.slice(0, 100)}...`;
}

/**
 * 모든 유형 목록 반환
 */
export function getAllTypes(): MBTIType[] {
  return Object.keys(typeDescriptions) as MBTIType[];
}
